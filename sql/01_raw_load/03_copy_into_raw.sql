-- 03_copy_into_raw.sql
-- Copies each staged CSV into its RAW table, then counts rows to confirm the load.

USE WAREHOUSE OLIST_WH;
USE DATABASE OLIST;
USE SCHEMA RAW;

COPY INTO CUSTOMERS      FROM @OLIST_STAGE PATTERN = '.*olist_customers_dataset.*';
COPY INTO GEOLOCATION    FROM @OLIST_STAGE PATTERN = '.*olist_geolocation_dataset.*';
COPY INTO ORDER_ITEMS    FROM @OLIST_STAGE PATTERN = '.*olist_order_items_dataset.*';
COPY INTO ORDER_PAYMENTS FROM @OLIST_STAGE PATTERN = '.*olist_order_payments_dataset.*';
COPY INTO ORDER_REVIEWS  FROM @OLIST_STAGE PATTERN = '.*olist_order_reviews_dataset.*';
COPY INTO ORDERS         FROM @OLIST_STAGE PATTERN = '.*olist_orders_dataset.*';
COPY INTO PRODUCTS       FROM @OLIST_STAGE PATTERN = '.*olist_products_dataset.*';
COPY INTO SELLERS        FROM @OLIST_STAGE PATTERN = '.*olist_sellers_dataset.*';
COPY INTO PRODUCT_CATEGORY_TRANSLATION FROM @OLIST_STAGE PATTERN = '.*product_category_name_translation.*';

-- Row counts per table
SELECT 'CUSTOMERS' AS table_name, COUNT(*) AS row_count FROM CUSTOMERS
UNION ALL SELECT 'GEOLOCATION', COUNT(*) FROM GEOLOCATION
UNION ALL SELECT 'ORDER_ITEMS', COUNT(*) FROM ORDER_ITEMS
UNION ALL SELECT 'ORDER_PAYMENTS', COUNT(*) FROM ORDER_PAYMENTS
UNION ALL SELECT 'ORDER_REVIEWS', COUNT(*) FROM ORDER_REVIEWS
UNION ALL SELECT 'ORDERS', COUNT(*) FROM ORDERS
UNION ALL SELECT 'PRODUCTS', COUNT(*) FROM PRODUCTS
UNION ALL SELECT 'SELLERS', COUNT(*) FROM SELLERS
UNION ALL SELECT 'PRODUCT_CATEGORY_TRANSLATION', COUNT(*) FROM PRODUCT_CATEGORY_TRANSLATION
ORDER BY table_name;